"""Porta de aplicação — abstração. Interface só conhece isto, nunca o service concreto."""
from __future__ import annotations

from typing import Protocol


class AppPort(Protocol):
    def init(self) -> None: ...
    def get_presets(self) -> dict: ...
    def calcular(self, dto: dict) -> dict: ...
    def listar(self, limit: int = 20) -> list[dict]: ...
    def listar_indices(self) -> list[dict]: ...
    def sincronizar(self, *, indice: str | None = None, tudo: bool = False, de: str = "2020-01", ate: str = "2026-10") -> int: ...
    def status_sync(self) -> dict: ...
